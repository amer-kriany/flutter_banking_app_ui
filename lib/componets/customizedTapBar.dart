class TapBar extends StatefulWidget {
  final ValueChanged<int>? onTabChanged;
  final int initialIndex;

  const TapBar({super.key, this.onTabChanged, this.initialIndex = 0});

  @override
  State<TapBar> createState() => _TapBarState();
}

class _TapBarState extends State<TapBar> {
  late int _selectedIndex;

  static const Color _color = Color(0xFF200E32);
  static const Color _chipBg = Color(0x0D250447);
  static const String _fontFamily = 'Mont';

  @override
  void initState() {
    super.initState();
    _selectedIndex = widget.initialIndex;
  }

  void _onTap(int index) async {
    if (_selectedIndex == index) return;
    setState(() => _selectedIndex = index);
    widget.onTabChanged?.call(index);
    await Future.delayed(const Duration(milliseconds: 300));

    final pages = [Wallet(), OffersPage(), Statistic(), settings()];
    Navigator.of(
      context,
    ).pushReplacement(MaterialPageRoute(builder: (context) => pages[index]));
  }

  @override
  Widget build(BuildContext context) {
    // ← كل tab عنده svgPath (inactive) و activeSvgPath (active/black)
    const tabs = [
      _TabData(
        label: 'Wallet',
        svgPath: _SvgPaths.wallet,
        activeSvgPath: _SvgPaths.blackWallet,
      ),
      _TabData(
        label: 'Offers',
        svgPath: _SvgPaths.star,
        activeSvgPath: _SvgPaths.blackStar,
      ),
      _TabData(
        label: 'Statistic',
        svgPath: _SvgPaths.graph,
        activeSvgPath: _SvgPaths.blackGraph,
      ),
      _TabData(
        label: 'Profile',
        svgPath: _SvgPaths.profile,
        activeSvgPath: _SvgPaths.blackProfile,
      ),
    ];

    return Container(
      color: Colors.white,
      child: SafeArea(
        top: false,
        child: SizedBox(
          height: 70,
          child: Padding(
            padding: const EdgeInsets.symmetric(horizontal: 20),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: List.generate(tabs.length, (i) {
                final isSelected = i == _selectedIndex;
                return _TapBarItem(
                  label: tabs[i].label,
                  // ← هنا: إذا selected استخدم activeSvgPath، غير كذا svgPath
                  svgPath: isSelected ? tabs[i].activeSvgPath : tabs[i].svgPath,
                  isSelected: isSelected,
                  color: _color,
                  chipColor: _chipBg,
                  fontFamily: _fontFamily,
                  onTap: () => _onTap(i),
                );
              }),
            ),
          ),
        ),
      ),
    );
  }
}

